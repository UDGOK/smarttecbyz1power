import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

export const pitchAssetSpecs = Object.freeze([
  ...['fiber','compute','campus'].flatMap(name=>[
    {action:`pitch-${name}-video`,filename:`${name}.mp4`,mime:'video/mp4'},
    {action:`pitch-${name}-poster`,filename:`${name}-poster.webp`,mime:'image/webp'}
  ]),
  {action:'pitch-vision-image',filename:'vision.webp',mime:'image/webp'}
]);
const repository=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const maxBytes=2_000_000;

export async function buildPitchMedia({root=repository,check=false}={}){
  const assets=[];
  for(const spec of pitchAssetSpecs){
    const path=resolve(root,'src/smarttec-investor/media/pitch',spec.filename);
    const bytes=await readFile(path);
    if(bytes.length<32||bytes.length>maxBytes)throw new Error(`${spec.filename}: expected 32–${maxBytes} bytes; got ${bytes.length}`);
    if(spec.mime==='video/mp4'&&bytes.toString('ascii',4,8)!=='ftyp')throw new Error(`${spec.filename}: invalid MP4 file signature`);
    if(spec.mime==='image/webp'&&(bytes.toString('ascii',0,4)!=='RIFF'||bytes.toString('ascii',8,12)!=='WEBP'||bytes.readUInt32LE(4)+8!==bytes.length))throw new Error(`${spec.filename}: invalid WebP file signature`);
    assets.push({...spec,bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex'),base64:bytes.toString('base64')});
  }
  const manifest={version:1,maxAssetBytes:maxBytes,access:'authenticated-investor-only',assets:assets.map(({base64,...metadata})=>metadata)};
  const registry=Object.fromEntries(assets.map(asset=>[asset.action,asset]));
  const outputs=[
    ['src/smarttec-investor/server/pitch-media.mjs',`// Generated by tools/build-pitch-media.mjs. Server-only: never import into client code.\nexport const pitchMedia = Object.freeze(${JSON.stringify(registry)});\n`],
    ['src/smarttec-investor/data/pitch-media.json',JSON.stringify(manifest,null,2)+'\n']
  ];
  for(const [relative,content] of outputs){
    const path=resolve(root,relative);
    if(check){if((await readFile(path,'utf8')).replaceAll('\r\n','\n')!==content)throw new Error(`Pitch media is stale: run node tools/build-pitch-media.mjs (${relative})`);}
    else{await mkdir(dirname(path),{recursive:true});await writeFile(path,content);}
  }
  return manifest;
}

if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const manifest=await buildPitchMedia({check:process.argv.includes('--check')});
  console.log(`Pitch media ${process.argv.includes('--check')?'verified':'built'}: ${manifest.assets.length} protected assets, ${manifest.assets.reduce((sum,asset)=>sum+asset.bytes,0)} bytes. No public copies created.`);
}
